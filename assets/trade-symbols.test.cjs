'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const symbols = require('./trade-symbols.js');
const folder = path.join(__dirname, 'trade-symbols');
const source = fs.readFileSync(path.join(__dirname, 'trade-symbols.js'), 'utf8');
const context = vm.createContext({});
vm.runInContext(source, context);
assert.equal(context.NDTradeSymbols.version, symbols.version, 'Browser global works without a DOM');
const all = symbols.list();
assert.equal(all.length, 36);
assert.equal(new Set(all.map(item => item.id)).size, all.length, 'Unique symbol IDs');
assert.equal(new Set(all.map(item => item.shorthand)).size, all.length, 'Unique shorthand');
assert.equal(new Set(all.map(item => item.code)).size, all.length, 'Unique Planner code');
assert.equal(symbols.categories().length, 6);
all.forEach(item => {
  assert.match(item.id, /^[a-z][a-z0-9-]+$/);
  assert.match(item.shorthand, /^[A-Z0-9]{1,4}$/, 'Planner shorthand is at most four characters');
  assert.ok(symbols.categories().some(category => category.id === item.category));
  const svg = symbols.svg(item.id);
  assert.match(svg, /viewBox="0 0 24 24"/);
  assert.match(svg, /stroke="currentColor"/);
  assert.match(svg, /role="img" aria-label="/);
  assert.match(svg, /<title>/);
  assert.doesNotMatch(svg, /(?:<script|on\w+=|href=|url\(|<foreignObject)/i);
  assert.equal(fs.readFileSync(path.join(folder, item.id + '.svg'), 'utf8'), symbols.svg(item.id, { size: 24, color: '#000' }) + '\n', 'Download matches API: ' + item.id);
});
assert.equal(symbols.list({ category: 'data' }).length, 9);
assert.equal(symbols.list({ category: 'all' }).length, 36);
assert.equal(symbols.list({ category: 'missing' }).length, 0);
assert.equal(symbols.list({ query: '  WAP  ' })[0].id, 'wireless-ap');
assert.equal(symbols.list({ query: 'fibre', category: 'cctv' }).length, 0);
assert.equal(symbols.list({ query: 'fibre' }).length, 2);
const mutated = symbols.list();
mutated[0].label = 'Changed';
assert.equal(symbols.list()[0].label, 'Single data outlet', 'Metadata cannot mutate the library');
const mutatedCategory = symbols.categories();
mutatedCategory[0].label = 'Changed';
assert.equal(symbols.categories()[0].label, 'Data & networking');
assert.equal(symbols.svg('missing'), '');
assert.equal(symbols.svg('__proto__'), '');
assert.equal(symbols.svg({ toString: () => 'rack' }), '');
assert.match(symbols.svg('rack', { size: 40, color: '#abcdef' }), /width="40" height="40".*stroke="#abcdef"/);
assert.match(symbols.svg('rack', { size: '48', color: 'white' }), /width="48" height="48".*stroke="white"/);
assert.match(symbols.svg('rack', { title: '' }), /aria-hidden="true"/);
assert.doesNotMatch(symbols.svg('rack', { title: '' }), /<title>|role="img"/);
for (const color of ['red" onload="alert(1)', 'url(https://example.com/asset.svg)', 'var(--injected)', '#abc; color:red']) {
  assert.match(symbols.svg('rack', { color }), /stroke="currentColor"/);
  assert.doesNotMatch(symbols.svg('rack', { color }), /onload=|https:|var\(|color:red/);
}
for (const size of [0, -5, 999, Infinity, NaN, '24" onload="bad']) {
  assert.match(symbols.svg('rack', { size }), /width="24" height="24"/);
}
const payload = '<img src=x onerror="bad"> & \' <script>bad</script>\u0000';
const escapedSvg = symbols.svg('rack', { title: payload });
assert.doesNotMatch(escapedSvg, /<img|<script|\u0000/);
assert.match(escapedSvg, /&lt;img src=x onerror=&quot;bad&quot;&gt; &amp; &#39;/);
const print = symbols.legend(['rack', 'rack', 'missing', '__proto__', 'single-gpo'], { title: payload });
assert.match(print, /^<!doctype html>/);
assert.match(print, /@media print/);
assert.match(print, /<thead>/);
assert.match(print, /2 symbols/);
assert.doesNotMatch(print, /<img|<script|\u0000/);
assert.equal((print.match(/<tbody>/g) || []).length, 1);
assert.equal((print.match(/<tr>/g) || []).length, 3, 'Header plus two deduplicated rows');
assert.match(symbols.legend([]), /No symbols selected/);
assert.match(symbols.legend('rack'), /1 symbol</);
assert.match(symbols.legend({}), /No symbols selected/);
const csv = symbols.categoryCsv(['rack', 'rack', 'missing', 'data-single']);
const lines = csv.trimEnd().split('\r\n');
assert.equal(lines[0], 'Item,Code,Description,Color,Shorthand');
assert.equal(lines.length, 3, 'CSV deduplicates and ignores unknown IDs');
assert.equal(lines[1], 'Communications rack,ND-RACK,Communications cabinet or equipment rack.,#3b82f6,RACK');
assert.match(symbols.categoryCsv(['ptz-camera']), /"Camera with pan, tilt and zoom movement\."/, 'CSV quotes descriptions containing commas');
assert.equal(symbols.categoryCsv([]), 'Item,Code,Description,Color,Shorthand\r\n');
assert.equal(fs.readFileSync(path.join(folder, 'planner-categories.csv'), 'utf8'), symbols.categoryCsv());
assert.equal(fs.readFileSync(path.join(folder, 'legend.html'), 'utf8'), symbols.legend());
const catalog = JSON.parse(fs.readFileSync(path.join(folder, 'catalog.json'), 'utf8'));
assert.deepEqual(catalog.symbols, all);
assert.deepEqual(catalog.categories, symbols.categories());
const sprite = fs.readFileSync(path.join(folder, 'sprite.svg'), 'utf8');
assert.equal((sprite.match(/<symbol /g) || []).length, all.length);
all.forEach(item => assert.ok(sprite.includes('id="nd-trade-' + item.id + '"'), 'Sprite contains ' + item.id));
const legendSvg = fs.readFileSync(path.join(folder, 'legend.svg'), 'utf8');
assert.equal((legendSvg.match(/transform="translate/g) || []).length, all.length);
assert.match(legendSvg, /aria-labelledby="legend-title legend-desc"/);
assert.doesNotMatch(legendSvg, /<script|href=|<foreignObject/i);
console.log('Trade symbol tests passed: 36 symbols, metadata, browser API, sanitization, filtering, Planner CSV and matching downloads.');
